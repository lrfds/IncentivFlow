export function t(path: string): string {
  const keys = path.split('.');
  let current: any = ptBR;
  for (const key of keys) {
    if (current != null && typeof current === 'object' && key in current) {
      current = current[key];
    } else {
      return path;
    }
  }
  return typeof current === 'string' ? current : path;
}
